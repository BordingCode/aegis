// `waves` is an array of DISCRETE waves; each wave is a list of spawn specs that
// emit `count` of `enemy` into `lane`, `gap` seconds apart, `delay` after the wave
// starts. A wave is cleared when all its enemies are dead -> boon pick -> next wave.
//
// LEVELS is the ordered RUN: a gauntlet of maps across three Acts. Map 1 is hand-
// authored and balanced (the regression test pins it); the rest are generated by
// makeLevel() on an escalating difficulty curve, and per-map `enemyScale` toughens
// foes to keep pace with the boons the player stacks as the run goes on.

